def build_pareto_variants_legend():
    variant_entries = [(_marker_entry(_safe_name(a), variant_marker(a)), a) for a in VARIANT_ORDER]
    key_entries = [
        (_marker_entry('gray', '^'), 'SLIM+ (sum)'),
        (_marker_entry('gray', 's'), 'SLIM* (mul)'),
        (_circle_entry('gray', True), 'Filled = Pareto-optimal'),
        (_circle_entry('gray', False), 'Hollow = dominated'),
    ]
    block1 = _block(variant_entries, N_COLS, 'Variant (color + shape)')
    block2 = _block(key_entries, 2, 'Shape / fill key', col_width=9.0)
    header = (
        '% Legend for pareto_variants.tex -- matplot2tikz drops fig.legend()\n'
        '% (it only walks per-axes legends, not fig-level ones), so this rebuilds it\n'
        '% with plain TikZ \\path/\\draw/\\node commands -- no tabular/center/\\\\ and no\n'
        '% \\usetikzlibrary calls (markers are hand-drawn triangles/squares/circles\n'
        '% via \\path, same technique matplot2tikz itself uses for pgfplots markers\n'
        '% in this file), so it is valid pasted directly INSIDE a tikzpicture. No\n'
        '% extra libraries needed. Paste this block right before the figure\'s own\n'
        '% \\end{tikzpicture} (i.e. after its existing suptitle \\draw(...) node{...} line).\n\n'
    )
    return header + '\n'.join(_color_defs()) + '\n\n' + _stack_blocks([block1, block2]) + '\n'


def build_pareto_baselines_legend():
    color_defs = [_hex_def('SLIMROLE', SLIM_COLOR)]
    color_defs += [_hex_def(a, BASELINE_STYLES[a]['color']) for a in BASELINE_KEYS]

    role_entries = [(_marker_entry(_hex_name('SLIMROLE'), ROLE_MARKERS[r]), f'SLIM -- {ROLE_LABELS[r]}')
                     for r in ROLE_MARKERS]
    baseline_entries = [(_marker_entry(_hex_name(a), BASELINE_STYLES[a]['marker']), a)
                         for a in BASELINE_KEYS]
    key_entries = [
        (_circle_entry('gray', True), 'Filled = Pareto-optimal'),
        (_circle_entry('gray', False), 'Hollow = dominated'),
    ]
    block1 = _block(role_entries + baseline_entries, 3, 'SLIM roles / baselines (color + shape)',
                     col_width=7.2)
    block2 = _block(key_entries, 2, 'Fill key', col_width=9.0)
    header = (
        '% Legend for pareto_baselines.tex -- matplot2tikz drops fig.legend()\n'
        '% (it only walks per-axes legends, not fig-level ones), so this rebuilds it\n'
        '% with plain TikZ \\path/\\draw/\\node commands -- no tabular/center/\\\\ and no\n'
        '% \\usetikzlibrary calls (markers are hand-drawn shapes via \\path, same\n'
        '% technique matplot2tikz itself uses for pgfplots markers in this file), so\n'
        '% it is valid pasted directly INSIDE a tikzpicture. No extra libraries needed.\n'
        '% Paste this block right before the figure\'s own \\end{tikzpicture} (i.e.\n'
        '% after its existing suptitle \\draw(...) node{...} line).\n\n'
    )
    return header + '\n'.join(color_defs) + '\n\n' + _stack_blocks([block1, block2]) + '\n'


def embed_legend_in_figure(figure_path, legend_body):
    """Splice legend_body directly into figure_path, right before its final
    \\end{tikzpicture}. Idempotent: re-running replaces a previously embedded
    block (delimited by LEGEND_BEGIN/LEGEND_END) instead of duplicating it."""
    with open(figure_path, 'r', encoding='utf-8') as f:
        content = f.read()

    block = f'\n{LEGEND_BEGIN}\n{legend_body}\n{LEGEND_END}\n'

    begin_idx = content.find(LEGEND_BEGIN)
    if begin_idx != -1:
        end_idx = content.find(LEGEND_END, begin_idx) + len(LEGEND_END)
        content = content[:begin_idx].rstrip('\n') + block + content[end_idx:].lstrip('\n')
    else:
        marker = '\\end{tikzpicture}'
        last = content.rfind(marker)
        if last == -1:
            raise ValueError(f'{figure_path}: no \\end{{tikzpicture}} found to splice legend before')
        content = content[:last] + block + content[last:]

    with open(figure_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'  Embedded legend -> {figure_path}')


if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)

    figures = {
        'evolution_rmse_grid.tex': build_evolution_rmse_legend(),
        'evolution_mphi_grid.tex': build_evolution_mphi_legend(),
        'pareto_variants.tex': build_pareto_variants_legend(),
        'pareto_baselines.tex': build_pareto_baselines_legend(),
    }
    standalone = {
        'legend_evolution_rmse.tex': figures['evolution_rmse_grid.tex'],
        'legend_evolution_mphi.tex': figures['evolution_mphi_grid.tex'],
        'legend_pareto_variants.tex': figures['pareto_variants.tex'],
        'legend_pareto_baselines.tex': figures['pareto_baselines.tex'],
    }
    for fname, content in standalone.items():
        path = os.path.join(OUT_DIR, fname)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f'  Saved -> {path}')

    for fname, legend_body in figures.items():
        embed_legend_in_figure(os.path.join(OUT_DIR, fname), legend_body)
